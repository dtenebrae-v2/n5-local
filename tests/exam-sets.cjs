const assert = require('node:assert/strict');
module.exports = async function examSetChecks(page,base) {
  const catalog = await (await page.request.get(base+'/api/exams')).json();
  await page.goto(base+'/jlpt/n5/exams');
  await page.locator('#exam-mixed').waitFor();
  if (!catalog.sets.every(s=>s.available)) return;
  const sets = await Promise.all(catalog.sets.map(async s=>(await page.request.get(base+'/api/exam?id='+s.id)).json()));
  const all=sets.flatMap(s=>s.sections.flatMap(section=>section.groups.flatMap(g=>g.items.map(q=>({...q,sectionId:section.id,examId:s.id})))));
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('n5.exam-sets.v1')));
  await page.locator('#exam-mixed').click();
  await page.locator('#exam-practice').click();
  let session=(await state()).sessions.mixed;
  assert.equal(session.keys.length,10);
  assert.equal(new Set(session.keys.map(id=>all.find(q=>q.id===id).family)).size,10);
  let q=all.find(q=>q.id===session.keys[0]);
  await page.waitForFunction(()=>[...document.querySelectorAll('.exam-fragment img')].every(i=>i.complete&&i.naturalWidth>0));
  assert.equal(await page.locator('.exam-document').count(),0);
  assert.equal(await page.locator('.exam-fragment').count(),q.media.length);
  assert.match(await page.locator('.exam-answer-panel').innerText(),new RegExp(`Ответ на вопрос №\\s*${q.number}`));
  assert.equal(await page.locator('select,input[type=radio]').count(),0);
  await page.keyboard.press(String(((q.correct+1)%q.choices)+1));
  const before=await page.locator('#exam-next').boundingBox();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#exam-feedback').getAttribute('data-status'),'incorrect');
  assert.equal((await page.locator('#exam-next').boundingBox()).y,before.y);
  await page.keyboard.press(String(q.correct+1));await page.keyboard.press('Enter');
  assert.equal(await page.locator('#exam-feedback').getAttribute('data-status'),'correct');
  assert.equal((await state()).sessions.mixed.answers[q.id].first,'incorrect');
  await page.keyboard.press('F1');await page.locator('dialog[open]').waitFor();
  await page.keyboard.press('Escape');await page.keyboard.press('Shift+Enter');
  assert.equal((await state()).sessions.mixed.index,1);
  await page.reload();await page.locator('#exam-mixed').click();await page.locator('#exam-resume').click();
  assert.equal((await state()).sessions.mixed.index,1);
  if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/exam-practice.png',fullPage:true});
  for (let i=1;i<10;i++)await page.locator('#exam-next').click();
  assert.match(await page.locator('#exam-summary').innerText(),/из 10/);

  await page.goto(base+'/jlpt/n5/exams/n5-2017');
  await page.locator('[data-exam-filter="listening"]').click();
  await page.locator('#exam-practice').click();
  session=(await state()).sessions['n5-2017'];
  q=all.find(q=>q.id===session.keys[0]);
  await page.waitForFunction(()=>document.querySelector('audio')?.readyState>=1);
  assert.ok(Math.abs(await page.locator('audio').evaluate(a=>a.currentTime)-q.clip[0])<1);
  await page.locator('[data-exam-rate="0.75"]').click();
  assert.equal(await page.locator('audio').evaluate(a=>a.playbackRate),.75);
  await page.locator('#exam-replay').click();
  await page.waitForFunction(()=>!document.querySelector('audio').paused);
  await page.keyboard.press('F3');assert.ok(await page.locator('audio').evaluate(a=>a.paused));
  await page.locator('audio').evaluate((a,end)=>{a.currentTime=end-.15;a.play();},q.clip[1]);
  await page.waitForFunction(()=>document.querySelector('audio').paused);
  while (!q.media.length) {
    await page.locator('#exam-next').click();
    session=(await state()).sessions['n5-2017'];q=all.find(q=>q.id===session.keys[session.index]);
  }
  await page.locator('.exam-fragment').first().click();
  await page.locator('[data-image-zoom="2"]').click();
  assert.ok(await page.locator('.exam-image-viewport').evaluate(e=>e.scrollWidth>e.clientWidth));
  await page.keyboard.press('Escape');
  await page.locator('#exam-source-pages').click();
  assert.equal(await page.locator('dialog img').count(),q.pages.length);
  await page.keyboard.press('Escape');
  for(const width of [320,390,1440]) {
    await page.setViewportSize({width,height:1000});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Exam overflow ${width}`);
    await page.locator('#exam-next').scrollIntoViewIfNeeded();
    const top=(await page.locator('#exam-next').boundingBox()).y;
    await page.keyboard.press(String(((q.correct+1)%q.choices)+1));await page.keyboard.press('Enter');
    assert.equal((await page.locator('#exam-next').boundingBox()).y,top,`Answer moves controls at ${width}`);
  }
  await page.keyboard.press(String(q.correct+1));await page.keyboard.press('Enter');
  await page.locator('#exam-reference').click();
  assert.ok(await page.locator('dialog img').count()>1);
  await page.keyboard.press('Escape');
  if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/exam-listening.png',fullPage:true});

  await page.goto(base+'/jlpt/n5/exams/n5-2013');
  await page.locator('#exam-start').click();await page.locator('#exam-begin-section').click();
  const deadline=(await state()).sessions['n5-2013'].deadline;
  await page.keyboard.press('2');
  assert.equal(await page.locator('#exam-feedback').innerText(),'');
  assert.equal(await page.locator('#exam-reveal').count(),0);
  await page.reload();await page.locator('#exam-resume').click();
  assert.equal((await state()).sessions['n5-2013'].deadline,deadline);
  assert.equal(await page.locator('[data-exam-choice="1"]').getAttribute('aria-pressed'),'true');
  // Simulate returning after this section's deadline; the next one must wait for a click.
  await page.goto(base+'/jlpt/n5/vocabulary');
  await page.evaluate(()=>{const p=JSON.parse(localStorage.getItem('n5.exam-sets.v1'));p.sessions['n5-2013'].deadline=Date.now()-1000;localStorage.setItem('n5.exam-sets.v1',JSON.stringify(p));});
  await page.goto(base+'/jlpt/n5/exams/n5-2013');await page.locator('#exam-resume').click();
  assert.match(await page.locator('#exam-study').innerText(),/Грамматика и чтение/);
  assert.equal((await state()).sessions['n5-2013'].ready,true);
  assert.equal(await page.locator('[data-exam-jump*="vocabulary"]').count(),0);
  await page.locator('#exam-begin-section').click();
  await page.locator('#exam-finish-section').click();await page.locator('dialog [data-confirm]').click();
  await page.locator('#exam-begin-section').click();
  await page.waitForFunction(()=>document.querySelector('audio')?.readyState>=1);
  await page.locator('#exam-play').click();
  await page.waitForFunction(()=>!document.querySelector('audio').paused);
  await page.evaluate(()=>{window.examOriginalAudio=document.querySelector('audio');});
  await page.locator('#exam-next').click();
  assert.ok(await page.evaluate(()=>document.querySelector('audio')===window.examOriginalAudio));
  await page.waitForTimeout(500);
  assert.ok(await page.locator('audio').evaluate(a=>!a.paused));
  await page.locator('#exam-finish-section').click();await page.locator('dialog [data-confirm]').click();
  await page.locator('#exam-summary').waitFor();
  await page.locator('[data-exam-review]').first().click();
  assert.ok(await page.locator('#exam-feedback').innerText());
  await page.locator('#exam-results').click();await page.locator('#exam-summary').waitFor();

  await page.goto(base+'/jlpt/n5/exams/n5-2012');
  await page.locator('.workbook-credits summary').click();
  assert.match(await page.locator('#content').innerText(),/не соответствует PDF/);
  await page.locator('[data-exam-unavailable]').click();
  assert.equal(await page.locator('dialog img').count(),4);
  await page.keyboard.press('Escape');
  await page.locator('[data-exam-filter="listening"]').click();
  assert.ok(await page.locator('#exam-practice').isDisabled());
  await page.goto(base+'/jlpt/n5/exams/n5-2021-12');
  await page.locator('#exam-start').click();
  for(let i=0;i<3;i++) {
    await page.locator('#exam-begin-section').click();
    await page.locator('#exam-finish-section').click();await page.locator('dialog [data-confirm]').click();
  }
  assert.equal(await page.locator('#exam-summary').innerText(),'Занятие завершено');
  assert.match(await page.locator('#exam-study').innerText(),/без проверенного ключа: 67/);
  await page.goto(base+'/jlpt/n5/vocabulary');
  assert.equal(await page.locator('audio').count(),0);
  console.log('PASS private exam sets, unique practice, OPUS clips, persistent timers, ungraded and mismatched sources');
};
