const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');

module.exports = async function addWordChecks(page, base) {
  await page.goto(base + '/jlpt/n5/vocabulary/complete');
  await page.waitForSelector('#results[aria-busy="false"]');
  const before = await (await page.request.get(base + '/api/health')).json();
  await page.locator('#add-word').click();
  await page.waitForSelector('.add-word-dialog[open]');
  const form = page.locator('#add-word-form');
  assert.equal(await form.evaluate(el => el.checkValidity()), false);
  await form.locator('[type=submit]').click();
  assert.equal((await (await page.request.get(base + '/api/health')).json()).entries, before.entries);
  await form.locator('[name=kanji]').fill('試験語');
  await form.locator('[name=kana]').fill('しけんご');
  await form.locator('[name=romaji]').fill('shikengo');
  await form.locator('[name=meaning]').fill('test vocabulary item');
  await form.locator('[name=collection][value="nouns"]').check();
  await page.waitForFunction(() => document.querySelector('#add-word-form [name=group]') && !document.querySelector('#new-group-label').disabled);
  assert.equal(await form.evaluate(el => el.checkValidity()), false);
  await form.locator('[name=group][value="nouns:study"]').check();
  assert.equal(await form.evaluate(el => el.checkValidity()), true);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('.add-word-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true);
  if (process.env.SCREENSHOT_DIR) {
    fs.mkdirSync(process.env.SCREENSHOT_DIR, { recursive: true });
    await page.screenshot({ path: path.join(process.env.SCREENSHOT_DIR, 'n5-add-word-mobile.png') });
  }
  await form.locator('[type=submit]').click();
  await page.waitForSelector('.add-word-dialog', { state: 'detached' });
  await page.waitForURL(/vocabulary\/nouns\?q=/);
  await page.waitForSelector('#results[aria-busy="false"]');
  assert.equal(await page.locator('.japanese-word').innerText(), '試験語');
  assert.match(await page.locator('#navigation a[href="/jlpt/n5/vocabulary/nouns"]').innerText(), /440/);
  await page.reload();
  await page.waitForSelector('#results[aria-busy="false"]');
  assert.equal(await page.locator('.japanese-word').innerText(), '試験語');
  await page.locator('#add-word').click();
  await form.locator('[name=kanji]').fill('試験語');
  await form.locator('[name=kana]').fill('しけんご');
  await form.locator('[name=romaji]').fill('shikengo');
  await form.locator('[name=meaning]').fill('test vocabulary item');
  await form.locator('[name=collection][value="nouns"]').check();
  await page.waitForFunction(() => document.querySelector('#add-word-form [name=group]') && !document.querySelector('#new-group-label').disabled);
  await form.locator('[name=group][value="nouns:study"]').check();
  await form.locator('[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#add-word-error').textContent.includes('уже есть'));
  assert.equal(await form.locator('[name=kanji]').inputValue(), '試験語');
  assert.equal((await (await page.request.get(base + '/api/health')).json()).entries, before.entries + 1);
  await form.locator('[name=collection][value="complete"]').check();
  assert.equal(await page.locator('#new-group-label').isVisible(), false);
  await form.locator('[name=collection][value="verbs"]').check();
  await page.waitForFunction(() => document.querySelector('#add-word-form [name=group]') && !document.querySelector('#new-group-label').disabled);
  assert.equal(await page.locator('#new-group-title').innerText(), 'Тип спряжения *');
  await page.locator('#add-reading').click();
  assert.equal(await form.evaluate(el => el.checkValidity()), false);
  await page.locator('.new-reading').last().locator('.remove-reading').click();
  await page.locator('#cancel-add-word').click();
  await page.waitForSelector('.add-word-dialog', { state: 'detached' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  console.log('PASS add-word required fields, group selection, persistence, duplicate errors and mobile layout');
};
