const { choose, openOptions } = require('./game-settings.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async function gameChecks(page, base) {
  await page.goto(base + '/jlpt/n5/practice');
  await page.waitForSelector('#game-question[data-word]');
  assert.equal(await page.locator('#navigation a.active').innerText(), 'Тренировка');
  await choose(page, '#game-kind input[value="nouns"]');
  assert.equal(await page.locator('select').count(), 0);
  const input = page.locator('#practice-answer');
  const feedback = page.locator('#practice-feedback');
  const question = page.locator('#game-question');
  const score = page.locator('#game-score');
  const submit = () => page.locator('#practice-form button[type=submit]').click();
  const expected = async () => {
    const reading = await question.locator('.practice-reading').innerText();
    const suffix = { past: 'でした', negative: 'じゃないです', past_negative: 'じゃなかったです' }[await question.getAttribute('data-form')];
    return reading + suffix;
  };
  assert.equal(await score.innerText(), 'С первой попытки: 0 из 0');
  await input.fill('がく');
  await input.press('F1');
  await page.waitForSelector('.practice-rules-dialog[open]');
  assert.equal(await page.locator('.rules-table .current-rule').count(), 1);
  assert.match(await page.locator('.rules-table').innerText(), /がくせいでした/);
  const wordBeforeRules = await question.getAttribute('data-word');
  await page.keyboard.press('Shift+Enter');
  assert.equal(await question.getAttribute('data-word'), wordBeforeRules);
  await page.keyboard.press('Escape');
  await page.waitForSelector('.practice-rules-dialog', { state: 'detached' });
  assert.equal(await input.inputValue(), 'がく');
  assert.equal(await input.evaluate(el => el === document.activeElement), true);
  await input.dispatchEvent('compositionstart');
  await input.press('Shift+Enter');
  assert.equal(await question.getAttribute('data-word'), wordBeforeRules);
  await input.dispatchEvent('compositionend');
  await input.fill(await expected());
  await submit();
  assert.equal(await feedback.getAttribute('data-status'), 'correct');
  await submit();
  assert.equal(await score.innerText(), 'С первой попытки: 0 из 1');
  const first = await question.getAttribute('data-word');
  await input.press('Shift+Enter');
  assert.notEqual(await question.getAttribute('data-word'), first);
  assert.equal(await input.inputValue(), '');
  assert.equal(await input.evaluate(el => el === document.activeElement), true);
  await submit();
  assert.equal(await feedback.getAttribute('data-status'), 'incorrect');
  assert.match(await feedback.innerText(), /Правильный ответ:/);
  assert.equal(await score.innerText(), 'С первой попытки: 0 из 2');
  await input.fill('でした');
  await submit();
  assert.equal(await feedback.getAttribute('data-status'), 'incorrect');
  await input.fill(await expected());
  await submit();
  assert.equal(await feedback.getAttribute('data-status'), 'correct');
  assert.equal(await score.innerText(), 'С первой попытки: 0 из 2');
  await page.locator('#game-next').click();
  await page.locator('#practice-reveal').click();
  assert.match(await feedback.innerText(), /Правильный ответ:/);
  assert.equal(await score.innerText(), 'С первой попытки: 0 из 3');
  await page.locator('#game-next').click();
  await page.locator('#game-next').click();
  assert.equal(await score.innerText(), 'С первой попытки: 0 из 4');
  await choose(page, '#game-kind input[value="verbs"]');
  await choose(page, '#game-mode input[value=all]');
  assert.equal(await score.innerText(), 'С первой попытки: 0 из 0');
  await choose(page, '#game-mode input[value=te]');
  assert.equal(await page.locator('#game-kind input[value=verbs]').isChecked(), true);
  for (let i = 0; i < 4; i++) {
    assert.equal(await question.getAttribute('data-form'), 'te');
    await input.press('Shift+Enter');
  }
  await page.locator('#practice-rules').click();
  await page.waitForSelector('.practice-rules-dialog[open]');
  assert.match(await page.locator('.practice-rules-dialog').innerText(), /ぐ → いで/);
  assert.match(await page.locator('.practice-rules-dialog').innerText(), /いく → いって/);
  assert.ok(await page.locator('.te-rules-table .ending-change').count() > 10);
  const changedEnding = page.locator('.te-rules-table .ending-change').filter({ hasText: /^って$/ }).first();
  assert.equal(await changedEnding.evaluate(el => getComputedStyle(el).color), 'rgb(40, 83, 69)');
  await page.setViewportSize({ width: 320, height: 640 });
  assert.equal(await page.locator('.practice-rules-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true);
  assert.equal(await page.locator('.practice-rules-dialog .rules-table').count(), 1);
  await page.locator('.practice-rules-dialog').evaluate(el => { el.scrollTop = el.scrollHeight; });
  assert.ok(await page.locator('.practice-rules-dialog .practice-close').isVisible());
  if (process.env.SCREENSHOT_DIR) await page.screenshot({ path: path.join(process.env.SCREENSHOT_DIR, 'n5-reference-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.keyboard.press('Escape');
  await page.waitForSelector('.practice-rules-dialog', { state: 'detached' });
  await choose(page, '#game-kind input[value=nouns]');
  assert.equal(await page.locator('#game-mode input[value=polite]').isChecked(), true);
  await choose(page, '#game-mode input[value=te]');
  assert.equal(await question.getAttribute('data-form'), 'te');
  await choose(page, '#game-mode input[value=all]');
  const seen = new Set();
  for (let i = 0; i < 12; i++) {
    const id = await question.getAttribute('data-word');
    // Skipped words are deliberately repeated after several questions.
    seen.add(id);
    await page.locator('#game-next').click();
  }
  await page.locator('#practice-rules').click();
  await page.waitForSelector('.practice-rules-dialog[open]');
  assert.match(await page.locator('.rules-table').innerText(), /かう|もらう/);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('.practice-rules-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await page.keyboard.press('Escape');
  await page.waitForSelector('.practice-rules-dialog', { state: 'detached' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await input.fill('あ');
  const before = await input.boundingBox();
  await input.press('Enter');
  assert.deepEqual(await input.boundingBox(), before);
  if (process.env.SCREENSHOT_DIR) {
    fs.mkdirSync(process.env.SCREENSHOT_DIR, { recursive: true });
    await page.screenshot({ path: path.join(process.env.SCREENSHOT_DIR, 'n5-game-mobile.png'), fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#navigation a[href="/jlpt/n5/vocabulary/verbs"]').click();
  await page.waitForSelector('#results[aria-busy="false"]');
  await page.goBack();
  await page.waitForSelector('#game-question[data-word]');
  console.log('PASS game full answers, first-attempt score, reveal, skip, filters, unique words, mobile and history');
};
