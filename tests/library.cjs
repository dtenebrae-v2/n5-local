const assert=require('node:assert/strict');
module.exports=async function libraryChecks(page,base) {
 const data=await (await page.request.get(base+'/api/library')).json();
 assert.equal(data.books.length,44);assert.ok(data.books.every(b=>[1,2].includes(b.level)));
 const book=data.books.find(b=>b.id==='61371');
 assert.ok(book.assets.pdf.available,'The reviewed sample is stored locally');
 assert.ok(book.assets.audio.available);
 const range=await page.request.get(base+book.assets.audio.local_url,{headers:{Range:'bytes=0-9'}});
 assert.equal(range.status(),206);assert.equal((await range.body()).length,10);assert.match(range.headers()['content-range'],/^bytes 0-9\//);
 const invalid=await page.request.get(base+book.assets.pdf.local_url,{headers:{Range:'bytes=999999999-'}});assert.equal(invalid.status(),416);
 await page.goto(base+'/jlpt/n5/library');
 await page.waitForSelector('.library-card');
 assert.equal(await page.locator('.library-card').count(),44);
 await page.locator('[data-level="2"]').click();assert.equal(await page.locator('.library-card').count(),19);
 await page.locator('#library-search').fill('鏡');assert.equal(await page.locator('.library-card').count(),1);
 await page.locator('.library-card .primary').click();
 await page.waitForSelector('#book-stage[aria-busy="false"]',{timeout:60000});
 assert.ok(await page.locator('#book-stage canvas').first().evaluate(c=>c.width>200&&c.height>200));
 assert.equal(book.pdf_pages,18);
 assert.equal(await page.locator('.pdfViewer .page').count(),18);
 assert.ok(await page.locator('#book-stage canvas').count()<10,'Only nearby pages are rendered');
 assert.equal(await page.locator('#book-total').innerText(),'/ 18');
 assert.equal(await page.locator('.textLayer').count(),0,'Text selection is deliberately disabled');
 await page.locator('#book-info-open').click();
 assert.match(await page.locator('#book-info .library-credits').innerText(),/池田あきつ/);
 assert.match(await page.locator('#book-info .library-credits').innerText(),/CC BY-NC-ND 4.0/);
 await page.keyboard.press('Escape');
 await page.locator('#book-next').click();
 await page.waitForFunction(()=>document.querySelector('#book-page')?.value==='2');
 await page.waitForFunction(()=>document.querySelector('#book-audio')?.readyState>=1);
 await page.locator('#book-audio').evaluate(a=>{a.currentTime=12;a.dispatchEvent(new Event('seeked'));});
 await page.locator('#book-rate').selectOption('1.25');
 await page.reload();await page.waitForSelector('#book-stage[aria-busy="false"]',{timeout:60000});
 await page.waitForFunction(()=>document.querySelector('#book-page')?.value==='2');
 await page.waitForFunction(()=>document.querySelector('#book-audio')?.currentTime>=11.5);
 assert.equal(await page.locator('#book-audio').evaluate(a=>a.playbackRate),1.25);
 await page.locator('#book-audio-forward').click();
 assert.ok(await page.locator('#book-audio').evaluate(a=>a.currentTime>=21.5));
 await page.locator('#book-audio-back').click();
 assert.ok(await page.locator('#book-audio').evaluate(a=>a.currentTime<13));
 await page.locator('#book-zoom-in').click();
 assert.equal(await page.locator('#book-fit').inputValue(),'custom');
 await page.locator('#book-fit').selectOption('page-width');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#book-page').fill('3');await page.locator('#book-page').press('Enter');
 await page.waitForFunction(()=>document.querySelector('#book-page')?.value==='3');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.ok(await page.locator('#book-stage').evaluate(el=>el.clientHeight>innerHeight*.6),'Book uses most of the mobile screen');
 await page.waitForTimeout(500); // PDF.js finishes refitting and restoring its anchor after resize.
 // Continuous scrolling moves the page counter without pressing navigation buttons.
 await page.locator('#book-stage').evaluate(stage=>{stage.scrollTop=stage.querySelector('[data-page-number="5"]').offsetTop+40;});
 await page.waitForFunction(()=>document.querySelector('#book-page')?.value==='5');
 assert.equal(await page.locator('.book-chrome-hidden').count(),0,'Programmatic page changes keep controls visible');
 const stageHeight=await page.locator('#book-stage').evaluate(el=>el.clientHeight);
 await page.locator('#book-stage').focus();
 await page.locator('#book-stage').hover();await page.mouse.wheel(0,250);
 await page.waitForSelector('.book-chrome-hidden');
 assert.ok(await page.locator('#book-stage').evaluate(el=>el.clientHeight)>stageHeight+50);
 assert.equal(await page.locator('.book-chrome').evaluate(el=>el.inert),true);
 await page.waitForTimeout(500);await page.mouse.wheel(0,-180);
 await page.waitForFunction(()=>!document.querySelector('.book-chrome-hidden'));
 await page.locator('#book-hide-controls').click();
 await page.locator('#book-show-controls').click();
 assert.equal(await page.locator('.book-chrome').evaluate(el=>el.inert),false);
 await page.locator('#book-thumbnails-open').click();
 assert.equal(await page.locator('.book-thumbnail').count(),18);
 await page.waitForSelector('.book-thumbnail canvas');
 await page.locator('.book-thumbnail[data-page="3"]').click();
 await page.waitForFunction(()=>document.querySelector('#book-page')?.value==='3');
 assert.equal(await page.locator('#book-thumbnails').evaluate(el=>el.open),false);
 // A real two-finger input sequence exercises the custom zoom path, not the +/- buttons.
 const touch=await page.context().newCDPSession(page);
 await touch.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:2});
 const box=await page.locator('#book-stage').boundingBox();
 const x=box.x+box.width/2,y=box.y+150;
 const scaleBefore=parseInt(await page.locator('#book-scale').innerText());
 const anchor=await page.locator('.page[data-page-number="3"]').evaluate((el,p)=>{const r=el.getBoundingClientRect();return {x:(p.x-r.left)/r.width,y:(p.y-r.top)/r.height};},{x,y});
 const points=d=>[{x:x-d,y,id:0},{x:x+d,y,id:1}];
 await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:points(35)});
 await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:points(70)});
 await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 await page.waitForFunction(before=>parseInt(document.querySelector('#book-scale').textContent)>before,scaleBefore);
 const after=await page.locator('.page[data-page-number="3"]').evaluate((el,a)=>{const r=el.getBoundingClientRect();return {x:r.left+a.x*r.width,y:r.top+a.y*r.height};},anchor);
 assert.ok(Math.abs(after.x-x)<8&&Math.abs(after.y-y)<8,'Pinch keeps the point under the fingers');
 assert.equal(await page.locator('.book-chrome-hidden').count(),0,'Pinching does not hide reader controls');
 await page.waitForTimeout(500);
 await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y:y+200,id:0}]});
 await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:y+100,id:0}]});
 await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x,y:y-30,id:0}]});
 await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 await page.waitForSelector('.book-chrome-hidden');
 await page.locator('#book-show-controls').click();
 await touch.send('Emulation.setTouchEmulationEnabled',{enabled:false});await touch.detach();
 await page.locator('#book-zoom-in').click();
 await page.locator('#book-stage').evaluate(el=>{el.scrollLeft=100;el.scrollTop+=90;});
 await page.waitForTimeout(350);
 const position=await page.locator('#book-stage').evaluate(el=>({left:el.scrollLeft,top:el.scrollTop}));
 await page.reload();await page.waitForSelector('#book-stage[aria-busy="false"]',{timeout:60000});
 await page.waitForFunction(p=>{const el=document.querySelector('#book-stage');return Math.abs(el.scrollLeft-p.left)<6&&Math.abs(el.scrollTop-p.top)<6;},position);
 assert.equal(await page.locator('#book-fit').inputValue(),'custom');
 // Width and whole-page fitting survive orientation changes, without document overflow.
 await page.locator('#book-fit').selectOption('page-fit');
 await page.setViewportSize({width:844,height:390});
 await page.waitForTimeout(350);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.setViewportSize({width:390,height:844});
 await page.locator('#book-fit').selectOption('page-width');
 await page.setViewportSize({width:320,height:640});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.ok(await page.locator('.book-controls').evaluate(el=>el.scrollWidth<=el.clientWidth));
 assert.ok(await page.locator('.book-audio').evaluate(el=>el.scrollWidth<=el.clientWidth));
 await page.setViewportSize({width:390,height:844});
 if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-library-reader-mobile.png'});
 await page.locator('#book-info-open').click();
 await page.locator('#book-completed').click();assert.equal(await page.locator('#book-completed').getAttribute('aria-pressed'),'true');
 await page.keyboard.press('Escape');
 await page.locator('.library-back').click();await page.waitForSelector('.library-card');
 await page.locator('[data-status=completed]').click();assert.equal(await page.locator('.library-card').count(),1);
 assert.match(await page.locator('.library-card h2').innerText(),/鏡/);
 await page.setViewportSize({width:320,height:640});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-library-catalog-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/jlpt/n5/vocabulary/complete');
 console.log('PASS library: continuous scroll, anchored pinch zoom, precise resume, thumbnails, audio, PDF numbering and mobile');
};
