const assert=require('node:assert/strict');
module.exports=async function libraryChecks(page,base) {
 const data=await (await page.request.get(base+'/api/library')).json();
 assert.equal(data.books.length,44);assert.ok(data.books.every(b=>[1,2].includes(b.level)));
 const book=data.books.find(b=>b.id==='61371');
 assert.ok(book.assets.pdf.available,'The reviewed sample is stored locally');
 assert.ok(book.assets.audio.available);
 const range=await page.request.get(base+book.assets.audio.local_url,{headers:{Range:'bytes=0-9'}});
 assert.equal(range.status(),206);assert.equal((await range.body()).length,10);assert.match(range.headers()['content-range'],/^bytes 0-9\//);
 const invalid=await page.request.get(base+book.assets.pdf.local_url,{headers:{Range:'bytes=999999999-'}});assert.equal(invalid.status(),416);
 await page.goto(base+'/jlpt/n5/library');
 await page.waitForSelector('.library-card');
 assert.equal(await page.locator('.library-card').count(),44);
 await page.locator('[data-level="2"]').click();assert.equal(await page.locator('.library-card').count(),19);
 await page.locator('#library-search').fill('鏡');assert.equal(await page.locator('.library-card').count(),1);
 await page.locator('.library-card .primary').click();
 await page.waitForSelector('#book-stage[aria-busy="false"]',{timeout:60000});
 assert.ok(await page.locator('#book-stage canvas').evaluate(c=>c.width>200&&c.height>200));
 assert.match(await page.locator('.library-credits').innerText(),/池田あきつ/);
 assert.match(await page.locator('.library-credits').innerText(),/CC BY-NC-ND 4.0/);
 await page.locator('#book-next').click();
 await page.waitForFunction(()=>document.querySelector('#book-page')?.value==='2'&&document.querySelector('#book-stage')?.getAttribute('aria-busy')==='false');
 await page.waitForFunction(()=>document.querySelector('#book-audio')?.readyState>=1);
 await page.locator('#book-audio').evaluate(a=>{a.currentTime=12;a.dispatchEvent(new Event('seeked'));});
 await page.locator('[data-rate="1.25"]').click();
 await page.reload();await page.waitForSelector('#book-stage[aria-busy="false"]',{timeout:60000});
 assert.equal(await page.locator('#book-page').inputValue(),'2');
 await page.waitForFunction(()=>document.querySelector('#book-audio')?.currentTime>=11.5);
 assert.equal(await page.locator('#book-audio').evaluate(a=>a.playbackRate),1.25);
 await page.locator('#book-zoom-in').click();await page.waitForSelector('#book-stage[aria-busy="false"]');
 await page.locator('#book-fit').click();await page.waitForSelector('#book-stage[aria-busy="false"]');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#book-page').fill('3');await page.locator('#book-page').press('Tab');
 await page.waitForFunction(()=>document.querySelector('#book-stage')?.getAttribute('aria-busy')==='false' && parseFloat(document.querySelector('#book-stage canvas')?.style.width)<=document.querySelector('#book-stage').clientWidth+1 && document.querySelector('#book-stage canvas')?.getAttribute('aria-label').startsWith('Страница 3 '));
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-library-reader-mobile.png',fullPage:true});
 await page.locator('#book-completed').click();assert.equal(await page.locator('#book-completed').getAttribute('aria-pressed'),'true');
 await page.locator('.library-back').click();await page.waitForSelector('.library-card');
 await page.locator('[data-status=completed]').click();assert.equal(await page.locator('.library-card').count(),1);
 assert.match(await page.locator('.library-card h2').innerText(),/鏡/);
 await page.setViewportSize({width:320,height:640});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-library-catalog-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/jlpt/n5/vocabulary/complete');
 console.log('PASS library: originals/credits, range requests, PDF rendering, page/audio resume, filters and mobile');
};
