const assert = require('node:assert/strict');
module.exports = async function workbookChecks(page, base) {
  await page.goto(base+'/jlpt/n5/workbooks');
  await page.locator('#content h1').waitFor();
  const catalog=await (await page.request.get(base+'/api/workbooks')).json();
  if(!catalog.books.find(b=>b.id==='somatome-n5-2017')?.available) return;
  const data=await (await page.request.get(base+'/api/workbook?id=somatome-n5-2017')).json();
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('n5.workbooks.v1')));
  await page.locator('a[href="/jlpt/n5/workbooks/somatome-n5-2017"]').click();
  await page.locator('[data-unit="w1d1"]').click();
  assert.equal(await page.locator('select').count(),0);
  const question=()=>page.locator('.workbook-prompt');
  assert.ok((await question().innerText()).includes('一人'));
  await page.keyboard.press('2');
  const before=await page.locator('#workbook-next').boundingBox();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'incorrect');
  assert.equal((await page.locator('#workbook-next').boundingBox()).y,before.y);
  await page.keyboard.press('1');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  assert.equal((await state()).books['somatome-n5-2017'].session.answers['p17-1'].first,'incorrect');
  await page.keyboard.press('Shift+Enter');
  assert.equal((await state()).books['somatome-n5-2017'].session.index,1);
  await page.reload();
  await page.locator('#workbook-resume').click();
  assert.ok((await question().innerText()).includes('お父さん'));
  await page.keyboard.press('F1');
  await page.locator('dialog[open]').waitFor();
  assert.ok((await page.locator('dialog').innerText()).includes('ひとり'));
  await page.keyboard.press('Escape');
  await page.locator('#workbook-contents').click();
  await page.locator('[data-week="6"]').click();
  await page.locator('[data-unit="w6d3"]').click();
  await page.locator('#workbook-audio').waitFor();
  await page.waitForFunction(()=>document.querySelector('#workbook-audio').readyState>=1);
  const source=await page.locator('#workbook-audio').getAttribute('src');
  assert.ok(source.endsWith('/Track002'));
  assert.equal(await page.locator('.workbook-choices img').count(),4);
  assert.ok(await page.locator('.workbook-choices img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0)));
  assert.equal(await page.locator('#workbook-feedback').innerText(),'');
  await page.locator('[data-audio-rate="0.75"]').click();
  assert.equal(await page.locator('audio').evaluate(a=>a.playbackRate),.75);
  await page.locator('[data-audio="toggle"]').click();
  await page.waitForFunction(()=>!document.querySelector('audio').paused);
  await page.keyboard.press('F3');
  assert.ok(await page.locator('audio').evaluate(a=>a.paused));
  await page.locator('audio').evaluate(a=>a.currentTime=12);
  await page.waitForTimeout(1200);
  await page.reload();await page.locator('#workbook-resume').click();
  await page.waitForFunction(()=>document.querySelector('audio').currentTime>=11);
  await page.keyboard.press('3');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  await page.locator('#workbook-feedback summary').click();
  assert.ok((await page.locator('#workbook-feedback').innerText()).includes('Ｔシャツ'));
  for(const width of [375,320,1440]) {
    await page.setViewportSize({width,height:1000});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
  }
  if(process.env.SCREENSHOT_DIR) await page.screenshot({path:process.env.SCREENSHOT_DIR+'/workbook-listening.png',fullPage:true});
  await page.locator('#workbook-contents').click();
  await page.locator('[data-week="3"]').click();await page.locator('[data-unit="w3d7"]').click();
  assert.ok((await page.locator('.workbook-passage').innerText()).includes('なっとう'));
  await page.keyboard.press('3');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  await page.locator('#workbook-contents').click();await page.locator('[data-week="1"]').click();
  await page.locator('[data-unit="w1d1"]').click();
  for(let i=0;i<3;i++)await page.locator('#workbook-next').click();
  assert.equal(await page.locator('.workbook-choices img').count(),4);
  await page.waitForFunction(()=>[...document.querySelectorAll('.workbook-choices img')].every(i=>i.complete&&i.naturalWidth>0));
  if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/workbook-kanji.png',fullPage:true});
  await page.locator('#workbook-contents').click();
  await page.locator('[data-unit="w1d7"]').click();
  for(let i=0;i<12;i++)await page.locator('#workbook-next').click();
  assert.ok((await question().innerText()).includes('えあこん'));
  await page.keyboard.press('4');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  await page.locator('#workbook-contents').click();await page.locator('#workbook-random').click();
  const keys=(await state()).books['somatome-n5-2017'].session.keys;
  assert.equal(keys.length,10);assert.equal(new Set(keys).size,10);
  assert.ok(keys.every(key=>data.items.find(q=>q.id===key).correct!==null));
  for(let i=0;i<10;i++)await page.locator('#workbook-next').click();
  assert.ok((await page.locator('#workbook-summary').innerText()).includes('из 10'));
  await page.goto(base+'/jlpt/n5/vocabulary');
  assert.equal(await page.locator('audio').count(),0);
};
