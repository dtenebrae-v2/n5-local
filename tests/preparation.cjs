const assert=require('node:assert/strict');
module.exports=async function preparationChecks(page,base) {
 await page.evaluate(()=>localStorage.removeItem('n5.preparation.v1'));
 await page.goto(base+'/jlpt/n5/preparation');
 await page.locator('.prep-topics summary').click();
 await page.locator('[data-topic=dates]').click();
 const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('n5.preparation.v1')));
 let saved=await read();const q=saved.session.questions[0];
 assert.equal(q.topic,'dates');
 await page.keyboard.press(String(q.correct+1));
 const before=await page.locator('[data-action=next]').boundingBox();
 await page.keyboard.press('Enter');
 assert.equal(await page.locator('#prep-feedback').getAttribute('data-correct'),'true');
 assert.match(await page.locator('#prep-feedback').innerText(),/Правильный ответ/);
 assert.equal((await page.locator('[data-action=next]').boundingBox()).y,before.y);
 saved=await read();assert.equal(saved.topics.dates.freshCorrect,1);
 await page.keyboard.press('Shift+Enter');
 await page.locator('[data-action=hint]').click();
 const second=(await read()).session.questions[1];
 await page.keyboard.press(String(second.correct+1));await page.keyboard.press('Enter');
 saved=await read();assert.equal(saved.topics.dates.hinted,1);assert.equal(saved.topics.dates.correct,1);
 await page.reload();await page.waitForSelector('#prep-feedback[data-correct]');
 assert.equal((await read()).topics.dates.attempts,2,'Restoring feedback does not count another answer');
 await page.keyboard.press('Shift+Enter');await page.locator('[data-action=unknown]').click();
 assert.equal((await read()).topics.dates.skipped,1);
 await page.keyboard.press('Shift+Enter');
 const current=(await read()).session.questions[(await read()).session.index].id;
 await page.goto(base+'/jlpt/n5/vocabulary/complete');await page.goto(base+'/jlpt/n5/preparation');await page.waitForSelector('#prep-heading');
 assert.equal((await read()).session.questions[(await read()).session.index].id,current);
 await page.locator('[data-action=home]').click();
 await page.locator('[data-start=weak]').click();
 saved=await read();assert.ok(saved.session.questions.every(v=>v.topic==='dates'));
 assert.ok(saved.session.questions[0].fresh,'Weak-topic practice prioritizes unseen examples');
 await page.locator('[data-action=home]').click();
 await page.setViewportSize({width:320,height:640});
 await page.locator('.prep-stats summary').first().click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.ok(await page.locator('.prep-stats .table-scroll').first().evaluate(el=>el.scrollWidth<=el.clientWidth+1));
 if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-preparation-stats-mobile.png',fullPage:false});
 await page.clock.fastForward(11*60000);
 await page.reload();await page.locator('[data-start=due]').click();
 assert.ok((await read()).session.questions.every(v=>v.topic==='dates'));
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/jlpt/n5/vocabulary/complete');
 console.log('PASS preparation: new examples, hints, saved session, no result jumps, topic schedule and mobile stats');
};
