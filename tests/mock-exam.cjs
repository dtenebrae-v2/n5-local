const assert = require('node:assert/strict');
module.exports = async function mockChecks(page, base) {
  await page.goto(base + '/jlpt/n5/mock');
  await page.getByRole('button',{name:'Начать тест',exact:true}).click();
  await page.waitForSelector('#mock-time');
  assert.equal(await page.locator('[data-index]').count(),20);
  const initial = await page.locator('.mock-question').innerText();
  await page.keyboard.press('2');
  await page.locator('[data-action=mark]').click();
  await page.reload(); await page.waitForSelector('#mock-time');
  assert.equal(await page.locator('.mock-question').innerText(),initial);
  assert.ok(await page.locator('[name=mock-choice][value="1"]').isChecked());
  assert.equal(await page.locator('[data-action=mark]').getAttribute('aria-pressed'),'true');
  await page.keyboard.press('ArrowRight'); assert.equal(await page.locator('[aria-current=step]').getAttribute('data-index'),'1');
  await page.locator('[data-action=end-block]').click();
  await page.locator('[data-cancel]').click(); assert.ok(await page.locator('#mock-time').isVisible());
  await page.locator('[data-action=end-block]').click(); await page.locator('[data-confirm]').click();
  assert.equal(await page.locator('.mock-review').count(),0);
  await page.getByRole('button',{name:'Начать второй блок'}).click();
  assert.equal(await page.locator('[data-index]').count(),29);
  // Expiry must finish the block and remain finished after reloading.
  await page.clock.install();
  await page.clock.fastForward(40*60000+1000);
  await page.reload(); await page.getByRole('button',{name:'Разобрать ответы'}).click();
  assert.equal(await page.locator('.mock-review').count(),49);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('n5.preparation.v1')).exams.length),1);
  await page.reload();await page.waitForSelector('#mock-heading');
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('n5.preparation.v1')).exams.length),1,'Reload does not import the exam twice');
  await page.getByRole('button',{name:'Разобрать ответы'}).click();
  await page.setViewportSize({width:320,height:640});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  if(process.env.SCREENSHOT_DIR) await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-mock-results.png',fullPage:true});
  await page.getByRole('button',{name:'Новый вариант'}).click();
  assert.ok(await page.locator('#mock-time').isVisible());
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  if(process.env.SCREENSHOT_DIR) await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-mock-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/jlpt/n5/vocabulary/complete');
  console.log('PASS mock N5: keyboard, saved answers/marks, section boundaries, expiration, review and mobile');
};
