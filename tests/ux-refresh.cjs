const assert = require('node:assert/strict');
const { choose, openSettings, openOptions } = require('./game-settings.cjs');
module.exports = async function uxChecks(page, base) {
  await page.evaluate(() => localStorage.removeItem('n5.training.v1'));
  await page.setViewportSize({ width: 390, height: 844 });
  const requests = [];
  const track = request => { if (request.url().includes('/api/')) requests.push(request.url()); };
  page.on('request', track);
  await page.goto(base + '/jlpt/n5/practice');
  await page.waitForSelector('#game-question[data-word]');
  page.off('request', track);
  assert.equal(requests.filter(url => url.includes('/api/training-words')).length, 1);
  assert.equal(requests.filter(url => url.includes('/api/words?')).length, 0);
  const input = page.locator('#practice-answer');
  assert.ok((await input.boundingBox()).y < 844, 'Answer is on the first mobile screen');
  await choose(page, '#game-kind input[value=nouns]');
  const originalId = await page.locator('#game-question').getAttribute('data-word');
  await input.fill('がく');
  await openSettings(page);
  await page.locator('#game-task input[value=grammar]').check();
  await page.locator('#settings-cancel').click();
  assert.equal(await input.inputValue(), 'がく');
  assert.equal(await page.locator('#game-question').getAttribute('data-word'), originalId);
  assert.equal(await page.locator('#game-task input[value=forms]').isChecked(), true);
  await openSettings(page);
  await page.locator('#game-task input[value=grammar]').check();
  await page.reload();
  await page.waitForSelector('#game-question[data-word]');
  assert.equal(await page.locator('#game-task input[value=forms]').isChecked(), true);
  assert.equal(await input.inputValue(), 'がく');
  await input.press('F1');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#game-score').innerText(), 'С первой попытки: 0 из 0');
  const reading = await page.locator('.practice-reading').innerText();
  const form = await page.locator('#game-question').getAttribute('data-form');
  await input.fill(reading + { past: 'でした', negative: 'じゃないです', past_negative: 'じゃなかったです' }[form]);
  const top = () => page.locator('#game-next').evaluate(el => el.getBoundingClientRect().top + scrollY);
  const before = await top();
  await input.press('Enter');
  assert.equal(await top(), before, 'Feedback must not move the next button');
  await page.locator('#game-finish').click();
  assert.equal(await page.evaluate(() => document.activeElement.id), 'game-summary-title');
  assert.equal(await page.locator('[data-result=hinted]').count(), 1);
  assert.equal(await page.locator('#game-repeat').isDisabled(), true);
  assert.ok(await page.locator('#game-summary').evaluate(el => el.scrollWidth <= el.clientWidth));
  if (process.env.SCREENSHOT_DIR) await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-ux-results-mobile.png',fullPage:true});
  await page.locator('#game-new').click();
  await openOptions(page);
  await page.locator('#game-keyboard > summary').click();
  await page.locator('[data-shortcut=next]').click();
  await page.keyboard.press('Control+r');
  assert.match(await page.locator('#shortcut-status').innerText(), /занято/);
  await page.keyboard.press('Escape');
  await page.locator('#settings-cancel').click();
  const beforeKeys = await page.locator('#game-question').getAttribute('data-word');
  await openOptions(page);
  await page.locator('[data-shortcut=next]').click();
  await page.keyboard.press('Control+ArrowRight');
  await page.locator('#settings-apply').click();
  assert.equal(await page.locator('#game-question').getAttribute('data-word'), beforeKeys);
  assert.match(await page.locator('#game-shortcuts').innerText(), /Ctrl\+ArrowRight/);
  await page.reload(); await page.waitForSelector('#game-question[data-word]');
  assert.match(await page.locator('#game-shortcuts').innerText(), /Ctrl\+ArrowRight/);
  if (process.env.SCREENSHOT_DIR) await page.screenshot({path:process.env.SCREENSHOT_DIR+'/n5-ux-practice-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/jlpt/n5/vocabulary/complete');
  await page.waitForSelector('#results[aria-busy=false]');
  assert.ok(await page.locator('[data-practice]').count() > 0);
  await page.locator('#next').click();
  await page.waitForSelector('#results[aria-busy=false]');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'results');
  assert.ok(Math.abs(await page.locator('#results').evaluate(el => el.getBoundingClientRect().top)) < 100);
  let fail = true;
  const failWords = route => fail ? (fail = false, route.fulfill({status:503,body:'{}'})) : route.continue();
  await page.route('**/api/words?*', failWords);
  await page.locator('#word-search').fill('school');
  await page.locator('#retry-words').click();
  await page.waitForSelector('#results[aria-busy=false]');
  assert.equal(await page.locator('#word-search').inputValue(), 'school');
  assert.ok(await page.locator('.word-table tbody tr').count());
  await page.unroute('**/api/words?*', failWords);
  await page.locator('#navigation a[href$="/grammar/nouns"]').click();
  await page.waitForSelector('.lesson');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'content');
  let failGame = true;
  const failTraining = route => failGame ? (failGame=false,route.fulfill({status:503,body:'{}'})) : route.continue();
  await page.route('**/api/training-words', failTraining);
  await page.goto(base+'/jlpt/n5/practice');
  await page.locator('#retry-page').click();
  await page.waitForSelector('#game-question[data-word]');
  await page.unroute('**/api/training-words', failTraining);
  console.log('PASS UX: settings transaction, hints, mobile actions/results, shortcuts, focus, unique loading and retry');
};
