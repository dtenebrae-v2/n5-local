const baseText = require('./base-text.cjs');
const assert = require('node:assert/strict');
module.exports = async function verbPhrases(page, base) {
  await page.goto(base + '/jlpt/n5/verb-phrases?word=8');
  await page.locator('#phrase-known').waitFor();
  await page.evaluate(() => localStorage.removeItem('n5-verb-phrases-v1'));
  await page.reload();
  await page.locator('#phrase-known').waitFor();
  assert.match(await baseText(page.locator('#phrase-study')), /窓を開ける/);
  assert.equal(await page.locator('#phrase-start').isDisabled(), true);
  await page.locator('#phrase-known').click();
  await page.reload();
  await page.locator('#phrase-known').waitFor();
  assert.match(await baseText(page.locator('#phrase-study')), /Знаю/);
  await page.locator('#phrase-status').selectOption('known');
  assert.match(await baseText(page.locator('#phrase-count')), /Выбрано: 1/);
  await page.locator('#phrase-mode').selectOption('full');
  await page.locator('#phrase-start').click();
  await page.locator('#practice-answer').fill('まどがあける');
  await page.locator('#practice-form button[type=submit]').click();
  assert.match(await baseText(page.locator('#practice-feedback')), /Неверно/);
  // An error removes the card from the "known" filter but must not change the active task.
  await page.locator('#practice-answer').fill('窓を開ける');
  await page.locator('#practice-form button[type=submit]').click();
  assert.match(await baseText(page.locator('#practice-feedback')), /Верно/);
  await page.locator('#phrase-task-next').click();
  assert.match(await baseText(page.locator('#phrase-task')), /0 из 1 с первой попытки/);
  await page.locator('#phrase-status').selectOption('learning');
  assert.match(await baseText(page.locator('#phrase-study')), /窓を開ける/);
  await page.locator('#phrase-mode').selectOption('verb');
  await page.locator('#phrase-start').click();
  assert.match(await baseText(page.locator('#phrase-task')), /窓を＿＿/);
  await page.locator('#practice-reveal').click();
  assert.match(await baseText(page.locator('#practice-feedback')), /開ける/);
  await page.locator('#phrase-task-next').click();
  assert.match(await baseText(page.locator('#phrase-task')), /С подсказкой/);
  await page.locator('#phrase-search').fill('zzzz');
  assert.match(await baseText(page.locator('#phrase-study')), /карточек нет/);
  assert.equal(await page.locator('#phrase-start').isDisabled(), true);
  await page.locator('#phrase-search').fill('');
  await page.locator('#phrase-status').selectOption('');
  await page.locator('#phrase-topic').selectOption('Дополнительные глаголы');
  assert.match(await baseText(page.locator('#phrase-count')), /Выбрано: 25/);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + '/jlpt/n5/vocabulary/verbs?q=' + encodeURIComponent('開ける'));
  await page.locator('a[href="/jlpt/n5/verb-phrases?word=8"]').click();
  await page.locator('#phrase-known').waitFor();
  assert.match(await baseText(page.locator('#phrase-study')), /窓を開ける/);
  await page.setViewportSize({ width: 1440, height: 1000 });
};
