const assert = require('node:assert/strict');
const baseText = require('./base-text.cjs');
module.exports = async function intensiveChecks(page, base) {
  const book = await (await page.request.get(base + '/api/workbook?id=intensive-n5')).json();
  assert.equal(book.items.length,110);
  await page.goto(base+'/jlpt/n5/workbooks');
  await page.locator('a[href="/jlpt/n5/workbooks/intensive-n5"]').click();
  assert.equal(await page.locator('[data-week]').count(),0);
  assert.equal(await page.locator('select').count(),0);
  assert.equal(await page.locator('#content').getByText('Неделя',{exact:false}).count(),0);
  await page.locator('[data-unit="listening-details"]').click();
  await page.locator('#workbook-audio').waitFor();
  await page.waitForFunction(()=>document.querySelector('audio').readyState>=1);
  assert.ok((await page.locator('audio').getAttribute('src')).endsWith('/Track063'));
  assert.equal(await baseText(page.locator('#workbook-feedback')),'');
  assert.equal(await page.locator('.workbook-transcript').count(),0);
  assert.equal(await page.locator('.workbook-choices img').count(),4);
  await page.locator('.workbook-choices img').first().waitFor();
  await page.keyboard.press('1');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'incorrect');
  assert.ok((await baseText(page.locator('.workbook-correct'))).includes('4'));
  await page.keyboard.press('4');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  await page.locator('#workbook-feedback summary').click();
  assert.ok((await baseText(page.locator('#workbook-feedback'))).includes('大きいかばん'));
  await page.locator('#workbook-feedback [data-enlarge]').click();
  await page.locator('dialog[open]').waitFor();
  await page.locator('[data-image-zoom="2"]').click();
  assert.ok(await page.locator('.exam-image-viewport').evaluate(e=>e.scrollWidth>=e.clientWidth));
  await page.keyboard.press('Escape');
  await page.reload();await page.locator('#workbook-resume').click();
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  const state=await page.evaluate(()=>JSON.parse(localStorage.getItem('n5.workbooks.v1')));
  assert.equal(state.books['intensive-n5'].session.answers['listening-63'].first,'incorrect');
  await page.locator('#workbook-contents').click();
  await page.locator('[data-unit="listening-expression"]').click();
  assert.ok((await page.locator('audio').getAttribute('src')).endsWith('/Track069'));
  assert.ok(!(await page.locator('.workbook-choices').innerText()).includes('行きませんか'));
  await page.keyboard.press('1');await page.keyboard.press('Enter');
  assert.ok((await baseText(page.locator('.workbook-correct'))).includes('いっしょに行きませんか'));
  await page.locator('#workbook-feedback summary').click();
  for(const width of [320,375,1440]) {
    await page.setViewportSize({width,height:900});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow ${width}`);
    await page.locator('.workbook-question > .workbook-image-button').click();
    await page.locator('[data-image-zoom="2"]').click();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Dialog overflow ${width}`);
    await page.keyboard.press('Escape');
  }
  await page.setViewportSize({width:375,height:900});
  if(process.env.SCREENSHOT_DIR) await page.screenshot({path:process.env.SCREENSHOT_DIR+'/intensive-listening.png',fullPage:true});
  await page.locator('#workbook-contents').click();await page.locator('[data-unit="listening-task"]').click();
  await page.keyboard.press('1');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'ungraded');
  await page.locator('#workbook-contents').click();
  await page.locator('[data-group="grammar-reading"]').click();await page.locator('[data-unit="grammar-2024"]').click();
  for(let i=0;i<9;i++) await page.locator('#workbook-next').click();
  await page.keyboard.press('1');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  assert.ok((await baseText(page.locator('#workbook-feedback'))).includes('そふが → くれた → カメラを → 毎日'));
  await page.locator('#workbook-contents').click();await page.locator('[data-unit="reading-2024"]').click();
  for(let i=0;i<4;i++) await page.locator('#workbook-next').click();
  await page.keyboard.press('1');await page.keyboard.press('Enter');
  assert.equal(await page.locator('#workbook-feedback').getAttribute('data-status'),'correct');
  assert.ok((await baseText(page.locator('#workbook-feedback'))).includes('とりの たかだ'));
  await page.locator('#workbook-contents').click();await page.locator('#workbook-random').click();
  const keys=await page.evaluate(()=>JSON.parse(localStorage.getItem('n5.workbooks.v1')).books['intensive-n5'].session.keys);
  assert.equal(keys.length,10);assert.equal(new Set(keys).size,10);
  assert.ok(keys.every(id=>book.items.find(q=>q.id===id).correct!==null));
  const tracks=await (await page.request.get(base+'/api/audio')).json();
  assert.equal(tracks.tracks.filter(t=>t.album==='Интенсив N5').length,24);
  await page.setViewportSize({width:1440,height:1000});
};
