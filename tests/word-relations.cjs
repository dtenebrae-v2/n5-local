const baseText = require('./base-text.cjs');
const assert = require('node:assert/strict');
module.exports = async function wordRelations(page, base) {
  await page.goto(base + '/jlpt/n5/word-relations');
  await page.locator('#relation-known').waitFor();
  await page.evaluate(() => { localStorage.removeItem('n5-word-relations-v1'); localStorage.removeItem('n5-word-relation-position'); });
  await page.reload();
  await page.locator('#relation-kind').selectOption('paraphrase');
  assert.match(await baseText(page.locator('#relation-study')), /暗い/);
  assert.match(await baseText(page.locator('#relation-study')), /明るくない/);
  assert.match(await baseText(page.locator('#relation-study')), /не точное равенство/);
  assert.equal(await page.locator('#relation-start').isDisabled(), true);
  await page.locator('#relation-known').click();
  await page.locator('#relation-status').selectOption('known');
  assert.match(await baseText(page.locator('#relation-count')), /Выбрано: 1/);
  await page.locator('#relation-start').click();
  assert.match(await baseText(page.locator('#relation-task')), /отрицание «明るい»/);
  await page.locator('#practice-answer').fill('くらい');
  await page.locator('#practice-form button[type=submit]').click();
  assert.match(await baseText(page.locator('#practice-feedback')), /Неверно/);
  await page.locator('#practice-answer').fill('明るくない');
  await page.locator('#practice-form button[type=submit]').click();
  assert.match(await baseText(page.locator('#practice-feedback')), /Верно/);
  await page.locator('#relation-task-next').click();
  assert.match(await baseText(page.locator('#relation-task')), /0 из 1 с первой попытки/);
  await page.locator('#relation-status').selectOption('learning');
  assert.match(await baseText(page.locator('#relation-study')), /明るくない/);
  await page.locator('#relation-start').click();
  await page.locator('#practice-reveal').click();
  await page.locator('#relation-task-next').click();
  assert.match(await baseText(page.locator('#relation-task')), /С подсказкой/);
  await page.reload();
  await page.locator('#relation-status').selectOption('learning');
  assert.match(await baseText(page.locator('#relation-study')), /暗い/);
  await page.locator('#relation-status').selectOption('');
  await page.locator('#relation-kind').selectOption('synonym');
  await page.locator('#relation-search').fill('お金');
  assert.match(await baseText(page.locator('#relation-count')), /Выбрано: 1/);
  await page.locator('#relation-learning').click();
  await page.locator('#relation-start').click();
  const source = await baseText(page.locator('#relation-task .phrase-japanese'));
  await page.locator('#practice-answer').fill(source === 'お金' ? 'かね' : 'おかね');
  await page.locator('#practice-form button[type=submit]').click();
  assert.match(await baseText(page.locator('#practice-feedback')), /Верно/);
  await page.locator('#relation-task-next').click();
  assert.match(await baseText(page.locator('#relation-task')), /1 из 1 с первой попытки/);
  await page.locator('#relation-search').fill('');
  await page.locator('#relation-kind').selectOption('antonym');
  await page.locator('#relation-search').fill('高い');
  assert.match(await baseText(page.locator('#relation-count')), /Выбрано: 2/);
  await page.locator('.phrase-directory summary').click();
  await page.locator('[data-relation="antonym-704-732"]').click();
  assert.match(await baseText(page.locator('#relation-study')), /Цена товара/);
  assert.match(await baseText(page.locator('#relation-study')), /安い/);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('#relation-search').fill('нет такого слова');
  assert.match(await baseText(page.locator('#relation-study')), /Карточек.*нет/);
  assert.equal(await page.locator('#relation-start').isDisabled(), true);
  await page.locator('#relation-search').fill('');
  await page.locator('#relation-kind').selectOption('paraphrase');
  await page.setViewportSize({width:1440,height:1000});
};
