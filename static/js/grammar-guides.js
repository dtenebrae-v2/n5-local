function block([title,model,explanation,example,note]) {
  return `<section class="rule-block"><span class="material-label">Правило</span><h2>${esc(title)}</h2><p class="rule-model" lang="ja">${highlightedRule(model)}</p><p>${esc(explanation)}</p>${ruleExample(example,esc)}${note ? `<aside class="rule-caution"><span class="material-label">Обратите внимание</span><p>${esc(note)}</p></aside>` : ''}</section>`;
}
export function grammarGuide(id,bank,catalog) {
  if (id === 'grammar') return `<article class="lesson" lang="ru"><p>Выберите тему: в каждом разделе есть правило, конструкция и пример с переводом.</p><div class="grammar-index">${catalog.lessons.filter(l=>l.id !== 'grammar').map(l=>`<a class="lesson-link" href="${l.path}">${esc(l.label)} →</a>`).join('')}</div></article>`;
  let rules = [...(GUIDES[id] || [])];
  if (id === 'grammar/nouns') rules = rules.concat(bank.rules.filter(r=>r.topic==='particles').map(r=>{
    const example = bank.exercises.find(q=>q.rule===r.id);
    const answer = example?.answers[0]?.written || example?.answers[0]?.kana || '';
    const sentence = example?.sentence.replace(/［[^］]*］/u,answer);
    return [r.label,r.label.split(' — ')[0],r.explanation,sentence ? `${sentence} — ${example.translation}` : ''];
  }));
  return `<article class="lesson grammar-guide" lang="ru">${rules.map(block).join('')}</article>`;
}
